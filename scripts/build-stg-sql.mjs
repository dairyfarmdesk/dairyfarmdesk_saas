// Builds ONE SQL file that creates the whole app inside a separate "stg" schema (staging), from the same migration
// files used for production, so staging cannot drift from production.
//   node scripts/build-stg-sql.mjs            -> supabase/stg/stg_schema.sql
// The result is run by hand in the Supabase SQL editor. It only ever touches the "stg" schema.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const FILES = ['0001_schema', '0002_helpers', '0003_rls', '0004_views', '0005_labour', '0006_cash', '0007_manager_access', '0008_milk_types_manager_delete', '0009_saas_tenancy']

export function buildStgSql() {
  const parts = [
    `-- GENERATED by scripts/build-stg-sql.mjs - do not edit by hand.`,
    `-- Creates the DairyFarmDesk staging copy in schema "stg". It never touches the "public" (production) schema.`,
    `-- Storage and auth are shared by the whole Supabase project, so storage policies are NOT created here.`,
    `create schema if not exists stg;`,
    `set search_path = stg;`,
    ``,
  ]
  for (const f of FILES) {
    let sql = readFileSync(join(ROOT, 'supabase/migrations', f + '.sql'), 'utf8')
    sql = sql.replace(/^create extension.*$/gim, '')
    if (f === '0003_rls') sql = sql.slice(0, sql.indexOf('-- Storage buckets'))            // storage is shared
    sql = sql.replace(/-- STORAGE-BEGIN[\s\S]*?-- STORAGE-END/g, '')
    sql = sql.replace(/set search_path = public/g, 'set search_path = stg').replace(/'public\./g, "'stg.")
    parts.push(`-- ===== ${f} =====`, sql, '')
  }
  parts.push(
    `-- ===== API access for the stg schema (Supabase gives this to "public" automatically) =====`,
    `grant usage on schema stg to anon, authenticated, service_role;`,
    `grant all on all tables in schema stg to anon, authenticated, service_role;`,
    `grant all on all sequences in schema stg to anon, authenticated, service_role;`,
    `alter default privileges in schema stg grant all on tables to anon, authenticated, service_role;`,
    `alter default privileges in schema stg grant all on sequences to anon, authenticated, service_role;`,
    `-- Then: Supabase -> Project Settings -> API -> Exposed schemas -> add "stg".`,
    `reset search_path;`,
  )
  return parts.join('\n')
}

// Optional step: copy production data into stg (run AFTER the schema file). Triggers are switched off while copying
// so the copy does not create audit-log rows or change updated_at.
export function buildCopySql() {
  const tables = ['farms', 'platform_admins', 'profiles', 'settings', 'animals', 'milk_production', 'customers', 'milk_sales', 'customer_payments',
    'expenses', 'medical_records', 'audit_log', 'labourers', 'labour_payments', 'cash_collections']
  const list = tables.map((t) => `'${t}'`).join(',')
  return `-- GENERATED: copies production data (schema public) into the staging schema (stg). Run once, after stg_schema.sql.
-- Only READS from public; only WRITES to stg. Existing rows in stg are removed first.
do $$
declare t text; cols text; vals text;
begin
  foreach t in array array[${list}] loop
    execute format('alter table stg.%I disable trigger user', t);
    execute format('truncate stg.%I cascade', t);
  end loop;
  foreach t in array array[${list}] loop
    -- columns are cast through text because stg has its own copies of the enum types (user_role, shift_t, ...)
    select string_agg(format('%I', c.column_name), ',' order by c.ordinal_position),
           string_agg(format('p.%I::text::%s', c.column_name,
             case when c.data_type = 'USER-DEFINED' then 'stg.' || c.udt_name else format_type(a.atttypid, a.atttypmod) end),
             ',' order by c.ordinal_position)
      into cols, vals
      from information_schema.columns c
      join pg_attribute a on a.attrelid = format('stg.%I', t)::regclass and a.attname = c.column_name
      where c.table_schema = 'stg' and c.table_name = t and c.is_generated = 'NEVER'
        and exists (select 1 from information_schema.columns p where p.table_schema = 'public' and p.table_name = t and p.column_name = c.column_name);
    execute format('insert into stg.%1$I (%2$s) select %3$s from public.%1$I p', t, cols, vals);
  end loop;
  foreach t in array array[${list}] loop
    execute format('alter table stg.%I enable trigger user', t);
  end loop;
  perform setval('stg.settings_id_seq', greatest(2, (select coalesce(max(id), 1) + 1 from stg.settings)), false);
end $$;
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(join(ROOT, 'supabase/stg'), { recursive: true })
  writeFileSync(join(ROOT, 'supabase/stg/stg_schema.sql'), buildStgSql())
  writeFileSync(join(ROOT, 'supabase/stg/copy_prod_to_stg.sql'), buildCopySql())
  console.log('wrote supabase/stg/stg_schema.sql and supabase/stg/copy_prod_to_stg.sql')
}
